"use strict";
const assert = require("node:assert/strict");
const layout = require("../WindowHelper/window-layout.js");
const geometry = {screen:{x:0,y:0,width:1200,height:832}, available:{x:0,y:0,width:1200,height:800}, dock:{x:200,y:3,width:800,height:94}};
let count = 0;
const check = (actual, expected) => { count++; assert.deepEqual(actual, expected); };
const r = (x,y,width,height) => ({x,y,width,height});
check(layout.adjust(r(0,0,1200,800),geometry).rect,r(0,105,1200,695));
check(layout.adjust(r(0,0,600,800),geometry).rect,r(0,105,600,695));
check(layout.adjust(r(600,0,600,800),geometry).rect,r(600,105,600,695));
check(layout.adjust(r(0,0,600,400),geometry).rect,r(0,105,600,347));
check(layout.adjust(r(600,400,600,400),geometry).rect,r(600,453,600,347));
check(layout.adjust(r(80,0,500,370),geometry),null);
check(layout.adjust(r(100,20,600,500),geometry),null);
check(layout.adjust(r(0,105,1200,695),geometry),null);
check(layout.classify(r(0,105,1200,695),geometry).source,r(0,0,1200,800));
const larger = {...geometry,dock:{...geometry.dock,height:130}};
check(layout.adjust(r(0,0,1200,800),larger).rect,r(0,141,1200,659));
const smaller = {...geometry,dock:{...geometry.dock,height:54}};
check(layout.adjust(r(0,0,1200,800),smaller).rect,r(0,65,1200,735));
check(layout.adjust(r(1300,0,1200,800),geometry),null);
check(layout.adjust(r(0,0,1200,NaN),geometry),null);
console.log(`PASS: ${count} maximize, tiling, floating-window and Dock reflow assertions`);
